// scripts/build_sql.mjs
// ============================================================================
//  Builds supabase/seed.sql from the ONE data source:
//      shared/data/servicesDatabase.json
//  using the same adapter as the website and the chat server.
//  Run after editing the database file:   npm run sql
// ============================================================================
import { readFileSync, writeFileSync } from 'node:fs'
import { normalizeDatabase } from '../shared/normalize.js'

const raw = JSON.parse(readFileSync(new URL('../shared/data/servicesDatabase.json', import.meta.url), 'utf8'))
const db = normalizeDatabase(raw)

/** SQL literal */
const q = (v) => {
  if (v === null || v === undefined) return 'null'
  if (typeof v === 'boolean') return v ? 'true' : 'false'
  if (typeof v === 'number') return String(v)
  if (Array.isArray(v)) return `array[${v.map(q).join(',')}]::text[]`
  return `'${String(v).replace(/'/g, "''")}'`
}
/** Insert rows, or update them if they already exist (keeps users' orders safe). */
const upsert = (table, cols, rows, key = ['id']) =>
  rows.length
    ? `insert into ${table} (${cols.join(', ')}) values\n${rows.map((r) => `(${r.map(q).join(', ')})`).join(',\n')}\n` +
      `on conflict (${key.join(', ')}) do update set ${cols.filter((c) => !key.includes(c)).map((c) => `${c} = excluded.${c}`).join(', ') || `${key[0]} = excluded.${key[0]}`};`
    : ''
const notIn = (table, ids) => `delete from ${table} where id not in (${ids.map(q).join(', ')});`

const m = db.meta
const seed = [
  '-- AUTO-GENERATED from shared/data/servicesDatabase.json by scripts/build_sql.mjs — do not edit.',
  '-- Re-running it updates the catalog in place: no truncate, so accounts, orders and chats are kept.',
  'begin;',
  upsert('meta', ['id', 'city', 'currency', 'currency_symbol', 'updated_at', 'disclaimer', 'districts'],
    [[1, m.city, m.currency, m.currencySymbol, m.updatedAt, m.disclaimer, db.districts]]),
  upsert('categories', ['id', 'title', 'icon', 'sort_order'], db.categories.map((c) => [c.id, c.title, c.icon, c.sortOrder])),
  upsert('services', ['id', 'category_id', 'name', 'price_from', 'price_to', 'unit', 'description', 'warranty', 'districts', 'source_olx', 'source_web', 'source_note', 'sort_order'],
    db.services.map((s, i) => [s.id, s.categoryId, s.name, s.priceFrom, s.priceTo, s.unit, s.description, s.warranty, s.districts, s.source.olx ?? null, s.source.web ?? null, s.source.note ?? '', i])),
  upsert('masters', ['id', 'name', 'title', 'type', 'category_ids', 'districts', 'location', 'experience_years', 'experience_label', 'response_time', 'response_minutes', 'url', 'olx_listing_id', 'note', 'verified', 'phone', 'phone_display', 'verified_at', 'sort_order'],
    db.masters.map((x, i) => [x.id, x.name, x.title, x.type, x.categoryIds, x.districts, x.location, x.experienceYears, x.experienceLabel, x.responseTime, x.responseMinutes, x.url, x.olxListingId, x.note, x.verified, x.phone, x.phoneDisplay, x.verifiedAt, i])),
  '-- links and stated prices are rebuilt from the file',
  'delete from master_services;',
  'delete from master_prices;',
  upsert('master_services', ['master_id', 'service_id'], db.masters.flatMap((x) => x.serviceIds.map((s) => [x.id, s])), ['master_id', 'service_id']),
  upsert('master_prices', ['master_id', 'service_id', 'price_from', 'price_to', 'source'], db.masters.flatMap((x) => x.prices.filter((p) => p.source !== 'own').map((p) => [x.id, p.serviceId, p.priceFrom, p.priceTo, p.source])), ['master_id', 'service_id']),
  '-- rows removed from the file are removed from the catalog',
  notIn('masters', db.masters.map((x) => x.id)),
  notIn('services', db.services.map((x) => x.id)),
  notIn('categories', db.categories.map((x) => x.id)),
  'commit;',
].join('\n\n') + '\n'

const read = (f) => readFileSync(new URL(`../supabase/migrations/${f}`, import.meta.url), 'utf8')
const setup = [
  '-- =====================================================================',
  '-- USTAM — full Supabase setup in ONE file.',
  '-- Supabase Dashboard → SQL Editor → New query → paste this file → Run.',
  '-- Creates the catalog + marketplace schema (RLS, triggers, realtime, storage)',
  `-- and loads all data from servicesDatabase.json (${db.categories.length} categories, ${db.services.length} services, ${db.masters.length} masters).`,
  '-- Safe to run again: it updates the catalog and keeps accounts, orders and chats.',
  '-- AUTO-GENERATED by `npm run sql` from supabase/migrations/* and the data file — do not edit.',
  '-- =====================================================================',
  '',
  '-- ######## 1. Catalog schema ########',
  read('20261118000000_catalog.sql'),
  '-- ######## 2. Marketplace: accounts, masters, orders, chat ########',
  read('20261118000100_marketplace.sql'),
  '-- ######## 3. Data from servicesDatabase.json ########',
  seed,
].join('\n')

writeFileSync(new URL('../supabase/seed.sql', import.meta.url), seed)
writeFileSync(new URL('../supabase/setup.sql', import.meta.url), setup)
console.log(`seed.sql + setup.sql: ${db.categories.length} categories, ${db.services.length} services, ${db.masters.length} masters`)
